const prompt = require("prompt-sync")();


console.log("Inserir notas de Nelliel:")
let Nelliel = (Number(prompt("Nota 1: ")) + Number(prompt("Nota 2: ")) 
            + Number(prompt("Nota 3: ")) + Number(prompt("Nota 4: "))) / 4;

if(Nelliel >= 6){
    console.log("Sua média é: ",Nelliel.toFixed(1),", você foi aprovado, parabéns!!" );
}else{
    console.log("Sua média é: ",Nelliel.toFixed(1),", você foi reprovado, mais sorte na próxima." );
}          

